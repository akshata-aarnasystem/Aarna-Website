/* build.js - bundles the header/footer, adds SEO tags to every page and builds sitemap.xml
   Usage:  node build.js
   Reads:  seo/seo.json (per-page title and description) and .env (SITE_URL)
   Writes: SEO block inside each page's <head>, sitemap.xml, and the Sitemap line in robots.txt
   No packages to install. */
const fs = require('fs');
const path = require('path');

const root = __dirname;
const read = (f) => fs.readFileSync(path.join(root, f), 'utf8');
const esc = (s) => String(s).replace(/&/g, '&amp;').replace(/"/g, '&quot;').replace(/</g, '&lt;').replace(/>/g, '&gt;');

function loadEnv() {
  const env = {};
  if (!fs.existsSync(path.join(root, '.env'))) return env;
  read('.env').split(/\r?\n/).forEach((line) => {
    const m = line.match(/^\s*([A-Z0-9_]+)\s*=\s*(.*?)\s*$/);
    if (m && !line.trim().startsWith('#')) env[m[1]] = m[2].replace(/^["']|["']$/g, '');
  });
  return env;
}

const env = Object.assign({}, loadEnv(), process.env);
const siteUrl = (env.SITE_URL || 'https://www.aarna.example').replace(/\/+$/, '');
const seo = JSON.parse(read('seo/seo.json'));
const site = seo.site;
const urlFor = (page) => (page === 'index.html' ? siteUrl + '/' : siteUrl + '/' + page);
const rel = (page, file) => (page.includes('/') ? '../' : '') + file;

function seoBlock(page, p) {
  const url = urlFor(page);
  const img = siteUrl + '/' + site.ogImage;
  const lines = [
    `<title>${esc(p.title)}</title>`,
    `<meta name="description" content="${esc(p.description)}">`,
    p.noindex ? '<meta name="robots" content="noindex, nofollow">' : '<meta name="robots" content="index, follow">',
    `<link rel="canonical" href="${url}">`,
    `<link rel="icon" type="image/png" href="${rel(page, site.favicon)}">`,
    `<meta property="og:type" content="website">`,
    `<meta property="og:site_name" content="${esc(site.name)}">`,
    `<meta property="og:locale" content="${esc(site.locale)}">`,
    `<meta property="og:title" content="${esc(p.title)}">`,
    `<meta property="og:description" content="${esc(p.description)}">`,
    `<meta property="og:url" content="${url}">`,
    `<meta property="og:image" content="${img}">`,
    `<meta name="twitter:card" content="summary_large_image">`,
    `<meta name="twitter:title" content="${esc(p.title)}">`,
    `<meta name="twitter:description" content="${esc(p.description)}">`,
    `<meta name="twitter:image" content="${img}">`,
  ];
  if (site.twitter) lines.push(`<meta name="twitter:site" content="${esc(site.twitter)}">`);
  // Structured data: keep it consistent with visible content and known site settings.
  const graph = [
    { '@type': 'Organization', '@id': siteUrl + '/#organization', name: site.name, url: siteUrl + '/', logo: siteUrl + '/assets/images/logo.png' },
    { '@type': 'WebSite', '@id': siteUrl + '/#website', name: site.name, url: siteUrl + '/', publisher: { '@id': siteUrl + '/#organization' } }
  ];
  if (page !== 'index.html') {
    const parts = page.replace(/\\.html$/, '').split('/');
    const label = (seo.pages[page].title || parts[parts.length - 1]).split(' | ')[0];
    const crumbs = [{ '@type': 'ListItem', position: 1, name: 'Home', item: siteUrl + '/' }];
    let pathSoFar = '';
    parts.forEach((part, i) => {
      pathSoFar += (pathSoFar ? '/' : '') + part;
      crumbs.push({ '@type': 'ListItem', position: i + 2, name: i === parts.length - 1 ? label : part.replace(/-/g, ' '), item: siteUrl + '/' + pathSoFar + '.html' });
    });
    graph.push({ '@type': 'BreadcrumbList', itemListElement: crumbs });
  }
  if (page === 'pages/services.html') graph.push({ '@type': 'Service', name: 'Digital growth services', provider: { '@id': siteUrl + '/#organization' }, areaServed: { '@type': 'Country', name: 'United States' }, serviceType: ['Digital strategy', 'Technical SEO', 'Website development', 'Marketing automation'] });
  if (page === 'pages/contact.html') graph.push({ '@type': 'ContactPage', name: seo.pages[page].title, url });
  if (page === 'pages/about.html') graph.push({ '@type': 'AboutPage', name: seo.pages[page].title, url, about: { '@id': siteUrl + '/#organization' } });
  if (page === 'pages/resources.html') graph.push({ '@type': 'CollectionPage', name: seo.pages[page].title, url });
  const ld = { '@context': 'https://schema.org', '@graph': graph };
  lines.push(`<script type="application/ld+json">${JSON.stringify(ld).replace(/</g, '\\u003c')}</script>`);
  return '<!-- SEO:START -->\n' + lines.join('\n') + '\n<!-- SEO:END -->';
}

// 0. components bundle, so the site also works when a page is opened by double-click (file://)
const comps = {};
fs.readdirSync(path.join(root, 'components')).filter((f) => f.endsWith('.html')).forEach((f) => { comps[f.replace(/\.html$/, '')] = read('components/' + f); });
fs.writeFileSync(path.join(root, 'assets/js/components.js'), '/* Generated by build.js from components/*.html - do not edit by hand. Lets the site work when opened by double-click. */\nwindow.AARNA_COMPONENTS = ' + JSON.stringify(comps) + ';\n');
console.log('bundle   assets/js/components.js');

// 1. SEO tags
const pages = Object.keys(seo.pages);
pages.forEach((page) => {
  const file = path.join(root, page);
  if (!fs.existsSync(file)) { console.warn('! listed in seo.json but missing: ' + page); return; }
  let html = fs.readFileSync(file, 'utf8');
  if (!/<!-- SEO:START -->[\s\S]*?<!-- SEO:END -->/.test(html)) { console.warn('! no SEO markers in ' + page); return; }
  html = html.replace(/<!-- SEO:START -->[\s\S]*?<!-- SEO:END -->/, seoBlock(page, seo.pages[page]));
  fs.writeFileSync(file, html);
  console.log('seo      ' + page);
});

// warn about pages that are not in seo.json
['.', 'pages'].forEach((dir) => {
  fs.readdirSync(path.join(root, dir)).filter((f) => f.endsWith('.html')).forEach((f) => {
    const p = dir === '.' ? f : dir + '/' + f;
    if (!seo.pages[p]) console.warn('! ' + p + ' is not listed in seo/seo.json (no SEO tags, not in sitemap)');
  });
});

// 2. sitemap.xml
const urls = pages.filter((p) => fs.existsSync(path.join(root, p)) && !seo.pages[p].noindex).map((p) => {
  const lastmod = fs.statSync(path.join(root, p)).mtime.toISOString().slice(0, 10);
  return `  <url>\n    <loc>${urlFor(p)}</loc>\n    <lastmod>${lastmod}</lastmod>\n    <changefreq>${seo.pages[p].changefreq || 'monthly'}</changefreq>\n    <priority>${seo.pages[p].priority || '0.5'}</priority>\n  </url>`;
});
fs.writeFileSync(path.join(root, 'sitemap.xml'), `<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n${urls.join('\n')}\n</urlset>\n`);
console.log('sitemap  sitemap.xml (' + urls.length + ' pages)');

// 3. robots.txt sitemap line
let robots = fs.existsSync(path.join(root, 'robots.txt')) ? read('robots.txt') : 'User-agent: *\nAllow: /\n';
robots = /^Sitemap:.*$/m.test(robots) ? robots.replace(/^Sitemap:.*$/m, 'Sitemap: ' + siteUrl + '/sitemap.xml') : robots.trimEnd() + '\n\nSitemap: ' + siteUrl + '/sitemap.xml\n';
fs.writeFileSync(path.join(root, 'robots.txt'), robots);
console.log('robots   robots.txt');
console.log('Done. Site URL: ' + siteUrl);
